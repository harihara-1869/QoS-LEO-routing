"""Run a saved Phase 1 scenario without a display or network downloads."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import random
import subprocess
import importlib.metadata
from logic_module import LogicalConfig
from setup import generate_omm_csv, get_satellite_data
from sim_man import SimulationManager
from traffic_module import Flow, FlowType


def run(scenario, output):
    config = json.loads(Path(scenario).read_text())
    if config.get('schema_version') != 1:
        raise ValueError('Unsupported scenario schema_version')
    duration, step = config['duration_s'], config['step_s']
    if not (math.isfinite(duration) and math.isfinite(step) and duration > 0 and step > 0):
        raise ValueError('duration_s and step_s must be positive and finite')
    names = [gs[0] for gs in config['ground_stations']]
    if len(names) != len(set(names)):
        raise ValueError('Ground station names must be unique')
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    random.seed(config['seed'])
    csv = output / 'constellation.csv'
    generate_omm_csv(str(csv), **config['constellation'], epoch=config['epoch'])
    satellites = get_satellite_data(csv_file=str(csv))
    sim = SimulationManager(satellites, config['epoch'], LogicalConfig(**config['links']), config['ground_stations'])
    for values in config['flows']:
        values = dict(values)
        values['flow_type'] = FlowType[values.get('flow_type', 'BULK')]
        flow = Flow(**values)
        if (flow.flow_id in sim.traffic.flows or flow.src not in names or flow.dst not in names
                or not 0 <= flow.start_time < flow.end_time
                or not math.isfinite(flow.end_time) or not math.isfinite(flow.data_rate_bps)
                or flow.data_rate_bps < 0 or flow.packet_size_bytes <= 0):
            raise ValueError('Invalid flow or unknown ground station')
        sim.traffic.flows[flow.flow_id] = flow
    # Include a final partial interval so non-integral durations conserve generated bytes.
    sim.core.schedule(0, 1, lambda time: sim.update_topology())
    previous = 0.0
    tick = 1
    while previous < duration:
        time = min(tick * step, duration)
        sim.core.schedule(time, 2, lambda now, interval: (sim.update_topology(), sim.traffic.on_packet_generation(now, interval)), time - previous)
        previous = time
        tick += 1
    sim.core.run(duration)
    result = {"schema_version": 1, "mode": "route_feasibility_only", "scenario": config,
              "summary": {"packets_generated": sum(f.packets_generated for f in sim.traffic.flows.values()),
                          "bytes_generated": sum(f.bytes_generated for f in sim.traffic.flows.values()),
                          "packets_with_route": sim.routed_packets, "packets_without_route": sim.unreachable_packets},
              "topology": sim.snapshots, "route_samples": sim.dataset}
    encoded = json.dumps(result, sort_keys=True, indent=2, allow_nan=False) + '\n'
    (output / 'results.json').write_text(encoded)
    revision = subprocess.run(['git', 'rev-parse', 'HEAD'], capture_output=True, text=True)
    manifest = {"result_sha256": hashlib.sha256(encoded.encode()).hexdigest(),
                "git_revision": revision.stdout.strip(),
                "working_tree_dirty": bool(subprocess.run(['git', 'status', '--porcelain'], capture_output=True, text=True).stdout),
                "source_sha256": {str(p): hashlib.sha256(p.read_bytes()).hexdigest()
                                   for p in sorted(Path('.').glob('*.py'))},
                "dependencies": {p: importlib.metadata.version(p) for p in ['numpy', 'skyfield', 'sgp4', 'igraph']}}
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    return result

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--scenario', default='scenarios/baseline.json')
    parser.add_argument('--output', default='runs/baseline')
    args = parser.parse_args()
    print(json.dumps(run(args.scenario, args.output)['summary'], indent=2))
